// One-time migration of the workspace's five platform-fact tables into `facts/<platform>/observed.ts`.
// Usage: node scripts/migrate-observed.ts [--workspace <dir>]
// Writes facts/<platform>/observed.ts, migration/legacy-fields.json and, for a platform without one, index.ts.
import { access } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { writeFormatted, stableJson } from './lib/format.ts'
import { defaultWorkspace, loadLegacyRows, toFact } from './lib/legacy.ts'
import type { LegacySidecar } from './lib/legacy.ts'
import type { Fact } from 'fact-kit'

const root = fileURLToPath(new URL('..', import.meta.url))
const { values } = parseArgs({ options: { workspace: { type: 'string' } } })
const rows = await loadLegacyRows(values.workspace ?? defaultWorkspace())

const byPlatform = new Map<string, Fact[]>()
const sidecars: Record<string, LegacySidecar> = {}
for (const row of rows) {
  const { fact, sidecar } = toFact(row)
  if (!byPlatform.has(row.platform)) byPlatform.set(row.platform, [])
  byPlatform.get(row.platform)?.push(fact)
  sidecars[fact.id] = { table: row.table, ...sidecar }
}

const INDEX = `import type { FactsModule } from 'fact-kit'
import { observed } from './observed.ts'

const entry: FactsModule = { describes: {}, facts: observed }

export default entry
`

for (const [platform, facts] of [...byPlatform].sort(([a], [b]) => a.localeCompare(b))) {
  const dir = join(root, 'facts', platform)
  const header =
    '// Generated by scripts/migrate-observed.ts from the workspace tables. Edit the facts here from now on.\n'
  await writeFormatted(
    join(dir, 'observed.ts'),
    `${header}import type { Fact } from 'fact-kit'\n\nexport const observed: Fact[] = ${JSON.stringify(facts)}\n`,
  )
  const index = join(dir, 'index.ts')
  if (
    !(await access(index).then(
      () => true,
      () => false,
    ))
  )
    await writeFormatted(index, INDEX)
  console.log(`${platform}: ${facts.length}`)
}
await writeFormatted(join(root, 'migration', 'legacy-fields.json'), `${stableJson(sidecars)}\n`)
console.log(`migrated ${rows.length} rows into ${byPlatform.size} platforms`)
